// Run against a disposable test environment with Chrome --remote-debugging-port=9223.
// Creates a qa* account for persistence checks; remove only that test account afterward.
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
const base=process.argv[2]||'http://localhost:8082';
const output=process.argv[3]||'target/auth-browser';
await mkdir(output,{recursive:true});
const tabs=await (await fetch('http://127.0.0.1:9223/json')).json();
const ws=new WebSocket(tabs.find(t=>t.type==='page').webSocketDebuggerUrl);
await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
let seq=0;const pending=new Map();
ws.onmessage=event=>{const m=JSON.parse(event.data);if(m.id){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(m.error):p.resolve(m.result);}};
const send=(method,params={})=>new Promise((resolve,reject)=>{const id=++seq;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}));});
const evaluate=async expression=>{const r=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw Error(r.exceptionDetails.exception?.description);return r.result.value;};
const wait=async expression=>{for(let n=0;n<150;n++){if(await evaluate(expression))return;await new Promise(r=>setTimeout(r,100));}throw Error('Timeout: '+expression);};
const click=selector=>evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
const screenshot=async name=>{const r=await send('Page.captureScreenshot',{format:'png'});await writeFile(path.join(output,name),Buffer.from(r.data,'base64'));};
const id='qa'+Date.now(), email=id+'@example.com',password='BrowserTest123!';
try{
 await send('Page.enable');await send('Network.enable');await send('Network.setCacheDisabled',{cacheDisabled:true});
 await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1100,deviceScaleFactor:1,mobile:false});
 await send('Page.navigate',{url:base+'/#home'});await wait("!!document.querySelector('#auth-form')");
 await click('#auth-form button[type=submit]');
 assert.equal(await evaluate("document.querySelector('#loginId-error').textContent"),'아이디를 입력해 주세요.');
 assert.equal(await evaluate("document.querySelector('#password-error').textContent"),'비밀번호를 입력해 주세요.');
 assert.equal(await evaluate("getComputedStyle(document.querySelector('#password-error')).color"),'rgb(180, 35, 56)');
 await screenshot('login-required.png');
 await evaluate("document.querySelector('#login-id').value='friend'");
 await click('#auth-form button[type=submit]');
 assert.equal(await evaluate("document.querySelector('#password-error').textContent"),'비밀번호를 입력해 주세요.');
 await click('a[href="#signup"]');await wait("document.querySelector('#auth-form')?.dataset.mode==='register'");
 await click('#auth-form button[type=submit]');
 assert.equal(await evaluate("document.querySelector('#email-error').textContent"),'이메일을 입력해 주세요.');
 await screenshot('register-required.png');
 await evaluate(`document.querySelector('#email').value=${JSON.stringify(email)};document.querySelector('#login-id').value=${JSON.stringify(id)};document.querySelector('#password').value=${JSON.stringify(password)};`);
 await click('#auth-form button[type=submit]');await wait("!!document.querySelector('[data-create-house]')");
 await evaluate("(async()=>{const {apiFetch}=await import('/api-client.js');const r=await apiFetch('/api/houses',{method:'POST'});if(!r.ok)throw Error('create house failed');location.hash='#house';})()");
 await wait("!!document.querySelector('.viewer-canvas')");
 const me=await evaluate("(async()=> (await fetch('/api/me')).json())()");
 assert.equal(me.user.displayName,id);
 await click('a[href="#edit"]');await wait("document.querySelectorAll('.furniture-card').length===11");
 // Use the catalog's keyboard click path; UI writes must carry the CSRF token.
 await click('[data-type="chair"]');
 await wait("document.querySelector('.editor-shell').dataset.saving==='false' && !!document.querySelector('[data-object=delete]:not(:disabled)')");
 await wait(`(async()=>{const h=await(await fetch('/api/houses/${me.user.houseId}')).json();return h.furniture.length===1;})()`);
 await click('[data-object="delete"]');
 await wait(`(async()=>{const h=await(await fetch('/api/houses/${me.user.houseId}')).json();return h.furniture.length===0;})()`);
 await click('#finish-edit');await wait("!!document.querySelector('.viewer-canvas')");
 await click('#logout');await wait("!!document.querySelector('#auth-form')");
 await evaluate(`document.querySelector('#login-id').value=${JSON.stringify(id)};document.querySelector('#password').value='WrongPassword123!';`);
 await click('#auth-form button[type=submit]');await wait("document.querySelector('#form-error').textContent.length>0");
 assert.equal(await evaluate("document.querySelector('#form-error').textContent"),'아이디 또는 비밀번호가 올바르지 않아요.');
 await evaluate(`document.querySelector('#password').value=${JSON.stringify(password)};`);
 await click('#auth-form button[type=submit]');await wait("!!document.querySelector('.viewer-canvas')");
 await send('Page.reload',{ignoreCache:true});await wait("!!document.querySelector('.viewer-canvas')");
 await screenshot('signed-in-house.png');
 await click('#logout');await wait("!!document.querySelector('#auth-form')");
 await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await click('#auth-form button[type=submit]');await screenshot('login-mobile.png');
 const forbidden=await evaluate("(async()=>{const r=await fetch('/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'});return r.status;})()");
 assert.equal(forbidden,403);
 await writeFile(path.join(output,'test-account.json'),JSON.stringify({id,email,houseId:me.user.houseId},null,2));
 console.log('PASS: required fields, signup, invalid/valid login, session reload, logout, CSRF, furniture add/delete; test account '+id);
}finally{ws.close();}
